#!/usr/bin/env bash
#
# Benchmarks secure-unzip against the system unzip and writes
# docs/benchmark/performance_report.md.
#
# Deliberately external rather than a Go benchmark: the headline claim is
# relative ("what does hardening cost versus plain unzip"), and testing.B
# cannot measure a foreign binary. See
# docs/agents/decisions/2026-08-06-hyperfine-for-benchmarks.md
set -euo pipefail

cd "$(dirname "$0")/.."

BIN="bin/secure-unzip"
FIXTURE_DIR="testdata/tmp"
ARCHIVE="$FIXTURE_DIR/large-benign.zip"
REPORT="docs/benchmark/performance_report.md"
SIZE_MB="${SIZE_MB:-200}"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

die() { echo "benchmark: $*" >&2; exit 1; }

# --- preflight -------------------------------------------------------------
command -v hyperfine >/dev/null 2>&1 || die "hyperfine not found (brew install hyperfine)"
command -v unzip     >/dev/null 2>&1 || die "system unzip not found — nothing to compare against"
[[ -x "$BIN" ]] || die "$BIN not built (run: make build-host)"

# GNU time is what reports Max RSS. macOS ships BSD time, which has no -v, so
# look for Homebrew's gtime and degrade gracefully rather than failing the run.
GNU_TIME=""
if command -v gtime >/dev/null 2>&1; then
  GNU_TIME="gtime"
elif /usr/bin/time -v true >/dev/null 2>&1; then
  GNU_TIME="/usr/bin/time"
fi

# --- fixture ---------------------------------------------------------------
echo "==> generating a ${SIZE_MB}MB benign archive"
mkdir -p "$FIXTURE_DIR"
go run ./cmd/genfixtures -d "$FIXTURE_DIR" -large-mb "$SIZE_MB" >/dev/null
[[ -f "$ARCHIVE" ]] || die "fixture generation produced no $ARCHIVE"

ARCHIVE_ABS="$(cd "$(dirname "$ARCHIVE")" && pwd)/$(basename "$ARCHIVE")"
BIN_ABS="$(cd "$(dirname "$BIN")" && pwd)/$(basename "$BIN")"

# --- timing ----------------------------------------------------------------
echo "==> hyperfine (3 warmup runs)"
HYPERFINE_MD="$WORK/hyperfine.md"
hyperfine \
  --warmup 3 \
  --runs 10 \
  --prepare "rm -rf $WORK/out && mkdir -p $WORK/out" \
  --command-name "secure-unzip" "$BIN_ABS -q -o -d $WORK/out $ARCHIVE_ABS" \
  --command-name "unzip"        "unzip -qq -o -d $WORK/out $ARCHIVE_ABS" \
  --export-markdown "$HYPERFINE_MD"

# --- resource usage --------------------------------------------------------
measure_rss() { # $1=label, $2...=command
  local label="$1"; shift
  if [[ -z "$GNU_TIME" ]]; then return; fi
  rm -rf "$WORK/out"; mkdir -p "$WORK/out"
  local raw
  raw="$($GNU_TIME -v "$@" 2>&1 >/dev/null || true)"
  local rss cpu
  rss="$(awk -F': ' '/Maximum resident set size/ {print $2}' <<<"$raw")"
  cpu="$(awk -F': ' '/Percent of CPU/ {print $2}' <<<"$raw")"
  echo "| $label | ${rss:-n/a} kB | ${cpu:-n/a} |"
}

RSS_TABLE=""
if [[ -n "$GNU_TIME" ]]; then
  echo "==> resource usage via $GNU_TIME"
  RSS_TABLE+="$(measure_rss "secure-unzip" "$BIN_ABS" -q -o -d "$WORK/out" "$ARCHIVE_ABS")"$'\n'
  RSS_TABLE+="$(measure_rss "unzip" unzip -qq -o -d "$WORK/out" "$ARCHIVE_ABS")"$'\n'
fi

# secure-unzip reports its own figures; not a benchmark, but a useful cross-check.
rm -rf "$WORK/out"; mkdir -p "$WORK/out"
SELF_REPORT="$("$BIN_ABS" -q -o -verbose -d "$WORK/out" "$ARCHIVE_ABS" 2>&1 >/dev/null || true)"

# --- report ----------------------------------------------------------------
mkdir -p "$(dirname "$REPORT")"
{
  echo "# Performance Report"
  echo
  echo 'Generated by `make bench` (`scripts/benchmark.sh`). Do not edit by hand — regenerate.'
  echo
  echo "* Date: $(date -u +%Y-%m-%d)"
  echo "* Platform: $(uname -s) $(uname -m)"
  echo "* Archive: ${SIZE_MB} MB uncompressed, $(basename "$ARCHIVE")"
  echo "* Baseline: \`$(command -v unzip)\`"
  echo
  echo "Figures are machine-specific. They must be regenerated on the machine you"
  echo "care about, not read from a committed report."
  echo
  echo "## Execution time"
  echo
  cat "$HYPERFINE_MD"
  echo
  echo "## Resource usage"
  echo
  if [[ -n "$RSS_TABLE" ]]; then
    echo "| Command | Max RSS | CPU |"
    echo "|---------|---------|-----|"
    printf '%s' "$RSS_TABLE"
  else
    echo "GNU \`time\` is not installed, so Max RSS and CPU percentage were not captured."
    echo "macOS ships BSD \`time\`, which has no \`-v\`. Install it with:"
    echo
    echo '```'
    echo "brew install coreutils   # provides gtime"
    echo '```'
  fi
  echo
  echo "## secure-unzip self-report"
  echo
  echo 'From `--verbose`. Single unwarmed run — not a benchmark result, shown for cross-reference.'
  echo
  echo '```'
  printf '%s\n' "$SELF_REPORT"
  echo '```'
} > "$REPORT"

echo "==> wrote $REPORT"
